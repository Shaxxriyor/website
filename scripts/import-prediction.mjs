// Import December Prediction Listening tests (one part each) from a folder of
// "Prediction test - Part N - Title.html" files.
// Like Listening Practice, the exam engine every page carries is moved to
// content/prediction/listening/_shared/ once and linked from each page.
// Writes content/prediction/listening/pred-l-pN-<title>.html and src/data/predictionListening.js.
// Run: node scripts/import-prediction.mjs "<folder>"   (then npm run add-tracker && npm run remove-timers)
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir || !existsSync(dir)) {
  console.error('Usage: node scripts/import-prediction.mjs "<folder with Prediction test - Part N - Title.html>"');
  process.exit(1);
}
const outDir = join('content', 'prediction', 'listening');
const sharedDir = join(outDir, '_shared');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(sharedDir, { recursive: true });

const slug = (s) =>
  s
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/['’‘`]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80);

const pages = [];
for (const file of readdirSync(dir)) {
  const m = file.match(/^Prediction test\s*-\s*Part\s*([1-4])\s*-\s*(.+)\.html$/i);
  if (!m) continue;
  const part = Number(m[1]);
  const title = m[2].trim();
  pages.push({ part, title, id: `pred-l-p${part}-${slug(title)}`, html: readFileSync(join(dir, file), 'utf8') });
}
pages.sort((a, b) => a.part - b.part || a.title.localeCompare(b.title));
if (new Set(pages.map((p) => p.id)).size !== pages.length) throw new Error('Two tests have the same name');

// Inline <script> / <style> blocks (no attributes), parsed the way the browser does.
const BLOCK = /<(script|style)>([\s\S]*?)<\/\1>/g;
const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);
const seen = new Map();
for (const p of pages) {
  for (const h of new Set([...p.html.matchAll(BLOCK)].filter((b) => b[2].length > 2000).map((b) => hash(b[0])))) {
    seen.set(h, (seen.get(h) || 0) + 1);
  }
}
const shared = new Set([...seen].filter(([, n]) => n === pages.length).map(([h]) => h));

const written = new Set();
let saved = 0;
const items = [];
for (const p of pages) {
  const html = p.html.replace(BLOCK, (block, tag, body) => {
    const h = hash(block);
    if (!shared.has(h)) return block;
    const name = `${h}.${tag === 'script' ? 'js' : 'css'}`;
    if (!written.has(name)) {
      writeFileSync(join(sharedDir, name), body);
      written.add(name);
    }
    saved += block.length;
    return tag === 'script' ? `<script src="_shared/${name}"></script>` : `<link rel="stylesheet" href="_shared/${name}">`;
  });
  writeFileSync(join(outDir, `${p.id}.html`), html);
  const questions = (html.match(/const LISTENING_ANSWERS\s*=\s*\{([\s\S]*?)\}/)?.[1].match(/"\d+"\s*:/g) ?? []).length || 10;
  items.push({ id: p.id, part: p.part, title: p.title, questions });
}

writeFileSync(
  join('src', 'data', 'predictionListening.js'),
  `// Generated by scripts/import-prediction.mjs — do not edit by hand.
// December Prediction, Listening: one IELTS Listening part per test, with audio.
export const predictionListening = ${JSON.stringify(items, null, 2)};
`,
);
console.log(`Imported ${items.length} tests (${[1, 2, 3, 4].map((n) => `Part ${n}: ${items.filter((i) => i.part === n).length}`).join(', ')}); ${written.size} shared files; ${(saved / 1e6).toFixed(0)} MB of duplicate code removed.`);
