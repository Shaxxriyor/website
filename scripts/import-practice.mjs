// Import Reading Practice passages from a folder laid out as
//   <dir>/Passage 1/Passage 1 - Title.html, <dir>/Passage 2/…, <dir>/Passage 3/…
// Copies them to public/practice/reading/ and regenerates src/data/readingPractice.js.
// Run: npm run import-practice -- "<dir>"   (then npm run add-tracker)
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const src = process.argv[2];
if (!src || !existsSync(src)) {
  console.error('Usage: npm run import-practice -- "<folder with Passage 1/2/3>"');
  process.exit(1);
}
const outDir = join('public', 'practice', 'reading');
mkdirSync(outDir, { recursive: true });

const slugify = (t) =>
  t.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 70);

const items = [];
const used = new Set();
for (const passage of [1, 2, 3]) {
  const dir = join(src, `Passage ${passage}`);
  if (!existsSync(dir)) continue;
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.html')).sort()) {
    const title = file.replace(/\.html$/, '').replace(/^Passage \d+\s*-\s*/, '').trim();
    let id = `p${passage}-${slugify(title)}`;
    for (let n = 2; used.has(id); n++) id = `p${passage}-${slugify(title)}-${n}`;
    used.add(id);
    const html = readFileSync(join(dir, file), 'utf8');
    const questions = (html.match(/"answer"\s*:/g) || []).length || null;
    writeFileSync(join(outDir, `${id}.html`), html);
    items.push({ id, passage, title, questions });
  }
}

const body = `// Generated by scripts/import-practice.mjs — do not edit by hand.
// Reading Practice: single passages in CDI format, grouped by passage number.
export const readingPractice = ${JSON.stringify(items, null, 2)};
`;
writeFileSync(join('src', 'data', 'readingPractice.js'), body);
console.log(`Imported ${items.length} passages (${[1, 2, 3].map((p) => items.filter((i) => i.passage === p).length).join(' / ')}).`);
