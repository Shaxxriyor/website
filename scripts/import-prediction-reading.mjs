// Import December Prediction Reading tests: "READING PREDICTION N.html" (+ "READING PREDICTION N.pdf")
// and the prediction table PDF.
// Writes content/prediction/reading/pred-r-test-N.html (+ .pdf), content/prediction/reading/table.pdf
// and src/data/predictionReading.js (with each test's passages from the teacher's table).
// Run: node scripts/import-prediction-reading.mjs "<folder with HTML/ and PDF/>" "<table.pdf>"
//      (then npm run add-tracker)
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [dir, table] = process.argv.slice(2);
if (!dir || !existsSync(join(dir, 'HTML'))) {
  console.error('Usage: node scripts/import-prediction-reading.mjs "<folder with HTML/ and PDF/>" ["<table.pdf>"]');
  process.exit(1);
}

// The passages of each test, from "December Prediction - Table" (×2 = appeared twice this month).
const PASSAGES = {
  1: ['The History of the Potato ×2', 'Growing More for Less ×2', 'The Voynich Manuscript ×2'],
  2: ['The History of the Chicken ×2', 'The Importance of Being Playful ×2', 'Memory Champions ×2'],
  3: ['Pluto Seen Up Close for the First Time ×2', 'Detection of a Meteorite Lake', 'The Tuatara - Past and Future'],
  4: ['A Brief History of Tea ×2', 'Corporate Social Responsibility', 'The Antikythera Mechanism'],
  5: ['James Hargreaves and the Spinning Jenny', 'Father of Modern Management 2', 'Facial Expression ×2'],
  6: ['The History of the British Wool Industry', 'Lean Production', 'Movement Underwater'],
  7: ['Traditional Maori Fishing Hooks', 'The Fashion Industry', 'A Closer Examination of a Study on Verbal and Non-verbal Messages'],
  8: ['The Impact of Environment on Children', "Dark Chocolate's Health-giving Benefits", 'Rights for Apes'],
  9: ['Studies in the History of Art and Visual Culture', 'Multi-tasking and the Brain', 'The Role of Mother Tongue in Education'],
  10: ['The Origins of Tennis', 'The Return of the Black-footed Ferret', 'Patient Safety (drug packaging)'],
  11: ['The Whale Goes to Court', 'Detection of a Meteorite Lake', 'Memory Champions ×2'],
  12: ['New Understanding of Giraffes in the Wild', 'The Importance of Being Playful ×2', 'The Voynich Manuscript ×2'],
  13: ['Investing in the Future', 'Growing More for Less ×2', 'The Tuatara - Past and Future'],
  14: ['Katsushika Hokusai', 'Father of Modern Management 2', 'Facial Expression ×2'],
  15: ['La Bella Principessa - A Question of Authorship', 'Corporate Social Responsibility', 'Science and Filmmaking'],
  16: ['The Life of Louis Braille', 'Muscle Loss', "Children's Literature Studies Today"],
  17: ['The Development of Plastics', 'The Constant Evolution of the Humble Tomato', 'Linguistic Diversity'],
  18: ['The Development of the Bicycle', 'Removing Unwanted Noise', 'Insect-inspired Robots'],
  19: ['Effect and Cause', 'King Croc', 'Mark Strizic - A Career of an Australian Photographer'],
  20: ['The Early History of Olive Oil', 'Stress Less', 'Seeing the Colour of Sounds, Hearing the Colour of Numbers'],
};

const outDir = join('content', 'prediction', 'reading');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const items = [];
for (const file of readdirSync(join(dir, 'HTML'))) {
  const m = file.match(/^READING PREDICTION (\d{1,2})\.html$/i);
  if (!m) continue;
  const no = Number(m[1]);
  const id = `pred-r-test-${no}`;
  writeFileSync(join(outDir, `${id}.html`), readFileSync(join(dir, 'HTML', file), 'utf8'));
  const pdf = join(dir, 'PDF', `READING PREDICTION ${no}.pdf`);
  const hasPdf = existsSync(pdf);
  if (hasPdf) copyFileSync(pdf, join(outDir, `${id}.pdf`));
  const passages = (PASSAGES[no] ?? []).map((t) => ({ title: t.replace(/\s*×2$/, ''), twice: /×2$/.test(t) }));
  items.push({ id, no, title: `Reading Prediction ${no}`, questions: 40, pdf: hasPdf, passages });
}
items.sort((a, b) => a.no - b.no);
if (table && existsSync(table)) copyFileSync(table, join(outDir, 'table.pdf'));

writeFileSync(
  join('src', 'data', 'predictionReading.js'),
  `// Generated by scripts/import-prediction-reading.mjs — do not edit by hand.
// December Prediction, Reading: full tests (3 passages, 40 questions) with the passages
// from the prediction table (twice = appeared twice in this month's exams).
export const predictionReading = ${JSON.stringify(items, null, 2)};
export const predictionTable = ${JSON.stringify(Boolean(table && existsSync(table)))};
`,
);
console.log(`Imported ${items.length} Reading Prediction tests (${items.filter((i) => i.pdf).length} with PDF)${table ? ' and the table' : ''}.`);
