// Import Listening Practice tests from folders of "Listening test N.html" files.
// Every test page carries the same ~0.9 MB exam engine (scripts and styles); those
// blocks are moved to content/practice/listening/_shared/ once and linked from
// each page, so 100+ tests stay small enough to deploy.
// Copies the pages to content/practice/listening/test-N.html and regenerates
// src/data/listeningPractice.js.
// Run: npm run import-listening -- "<dir>" ["<dir>" …]   (then npm run add-tracker)
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dirs = process.argv.slice(2);
if (!dirs.length || !dirs.every(existsSync)) {
  console.error('Usage: npm run import-listening -- "<folder with Listening test N.html>" […]');
  process.exit(1);
}
const outDir = join('content', 'practice', 'listening');
const sharedDir = join(outDir, '_shared');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(sharedDir, { recursive: true });

const pages = [];
for (const dir of dirs) {
  for (const file of readdirSync(dir)) {
    const m = file.match(/^Listening test (\d+)\.html$/i);
    if (m) pages.push({ no: Number(m[1]), html: readFileSync(join(dir, file), 'utf8') });
  }
}
pages.sort((a, b) => a.no - b.no);

// Inline <script> / <style> blocks (no attributes), parsed the way the browser
// does: a block ends at the first closing tag.
const BLOCK = /<(script|style)>([\s\S]*?)<\/\1>/g;
const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);

// Blocks that every page has, byte for byte, are the shared engine.
const seen = new Map();
for (const p of pages) {
  for (const h of new Set([...p.html.matchAll(BLOCK)].filter((b) => b[2].length > 2000).map((b) => hash(b[0])))) {
    seen.set(h, (seen.get(h) || 0) + 1);
  }
}
const shared = new Set([...seen].filter(([, n]) => n === pages.length).map(([h]) => h));

const written = new Set();
let saved = 0;
const items = [];
for (const p of pages) {
  const html = p.html.replace(BLOCK, (block, tag, body) => {
    const h = hash(block);
    if (!shared.has(h)) return block;
    const name = `${h}.${tag === 'script' ? 'js' : 'css'}`;
    if (!written.has(name)) {
      writeFileSync(join(sharedDir, name), body);
      written.add(name);
    }
    saved += block.length;
    return tag === 'script' ? `<script src="_shared/${name}"></script>` : `<link rel="stylesheet" href="_shared/${name}">`;
  });
  const id = `test-${p.no}`;
  writeFileSync(join(outDir, `${id}.html`), html);
  const questions = (html.match(/const LISTENING_ANSWERS\s*=\s*\{([\s\S]*?)\}/)?.[1].match(/"\d+"\s*:/g) ?? []).length || 40;
  items.push({ id, no: p.no, title: `Listening Test ${p.no}`, questions });
}

const body = `// Generated by scripts/import-listening.mjs — do not edit by hand.
// Listening Practice: full IELTS Listening tests (4 parts, 40 questions).
export const listeningPractice = ${JSON.stringify(items, null, 2)};
`;
writeFileSync(join('src', 'data', 'listeningPractice.js'), body);
console.log(`Imported ${items.length} tests; ${written.size} shared files; ${(saved / 1e6).toFixed(0)} MB of duplicate code removed.`);
